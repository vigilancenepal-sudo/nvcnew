// Flattened list of all 77 districts
export const ALL_NEPAL_DISTRICTS: string[] = Object.values(NEPAL_DISTRICTS_BY_PROVINCE).flat();

// Reverse map from Nepali district to province name
export const DISTRICT_TO_PROVINCE_MAP: Record<string, string> = {};
for (const [pNoStr, dists] of Object.entries(NEPAL_DISTRICTS_BY_PROVINCE)) {
  const pNo = Number(pNoStr);
  const pName = NEPAL_PROVINCE_NAMES[pNo] || '';
  for (const d of dists) {
    DISTRICT_TO_PROVINCE_MAP[d] = pName;
  }
}

// Map from district name (Nepali or English) to local levels
export function getLocalLevelsFromNepalData(district: string): string[] {
  if (!district) return [];
  const normalized = district.trim();
  
  // Try direct lookup
  for (const pNo of [1, 2, 3, 4, 5, 6, 7]) {
    const pMuns = NEPAL_MUNICIPALITIES[pNo];
    if (pMuns && pMuns[normalized]) {
      return pMuns[normalized];
    }
  }

  // Try via district name map (English -> Nepali)
  const upper = normalized.toUpperCase();
  const neName = NEPAL_DISTRICT_NAME_MAP[upper];
  if (neName) {
    for (const pNo of [1, 2, 3, 4, 5, 6, 7]) {
      const pMuns = NEPAL_MUNICIPALITIES[pNo];
      if (pMuns && pMuns[neName]) {
        return pMuns[neName];
      }
    }
  }

  // Fallback for partial / alternate matches (e.g., 'रुकुम (पूर्व)' vs 'पूर्वी रुकुम')
  for (const pNo of [1, 2, 3, 4, 5, 6, 7]) {
    const pMuns = NEPAL_MUNICIPALITIES[pNo];
    if (!pMuns) continue;
    for (const [dKey, munList] of Object.entries(pMuns)) {
      if (dKey.includes(normalized) || normalized.includes(dKey)) {
        return munList;
      }
    }
  }

  return [];
}

export function getProvinceForDistrictFromNepalData(district: string): string {
  if (!district) return 'बागमती प्रदेश';
  const normalized = district.trim();
  if (DISTRICT_TO_PROVINCE_MAP[normalized]) {
    return DISTRICT_TO_PROVINCE_MAP[normalized];
  }
  const upper = normalized.toUpperCase();
  const neName = NEPAL_DISTRICT_NAME_MAP[upper];
  if (neName && DISTRICT_TO_PROVINCE_MAP[neName]) {
    return DISTRICT_TO_PROVINCE_MAP[neName];
  }
  return 'बागमती प्रदेश';
}
